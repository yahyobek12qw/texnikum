export const dictionaries: Record<Locale, Dict> = { uz, ru, en };

export function translate(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[locale][key] ?? dictionaries.uz[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
